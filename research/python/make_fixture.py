#!/usr/bin/env python3
"""Regenerate the deterministic SYNTHETIC fixture used by offline tests.

This is NOT live market data. It exists so tests and the example report are
reproducible when exchange endpoints are unavailable. Use fetch_ohlcv.py for
real public Binance klines and label the resulting report data_kind=public_api.
"""
from __future__ import annotations

import argparse
import csv
import json
import math
from datetime import datetime, timedelta, timezone
from pathlib import Path

START = datetime(2025, 1, 1, tzinfo=timezone.utc)
ROWS = 360


def close_at(index: int) -> float:
    return max(1.0, 100.0 + 0.08 * index + 6.0 * math.sin(index / 9.0) + 2.5 * math.sin(index / 31.0))


def generate(rows: int = ROWS) -> list[dict[str, object]]:
    output: list[dict[str, object]] = []
    previous_close = close_at(0) * 0.999
    for index in range(rows):
        close = close_at(index)
        open_price = previous_close
        high = max(open_price, close) + 1.5 + abs(2.0 * math.sin(index / 4.0))
        low = min(open_price, close) - 1.0 - abs(1.5 * math.cos(index / 5.0))
        volume = 1000.0 + (index % 40) * 25.0 + 200.0 * abs(math.sin(index / 7.0))
        output.append({
            "timestamp": (START + timedelta(days=index)).isoformat().replace("+00:00", "Z"),
            "open": round(open_price, 6),
            "high": round(high, 6),
            "low": round(low, 6),
            "close": round(close, 6),
            "volume": round(volume, 6),
        })
        previous_close = close
    return output


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="research/python/fixtures/synthetic_btcusdt_1d.csv")
    parser.add_argument("--rows", type=int, default=ROWS)
    args = parser.parse_args(argv)
    if args.rows < 3:
        raise SystemExit("--rows minimal 3")
    rows = generate(args.rows)
    path = Path(args.output)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    provenance = {
        "data_kind": "synthetic",
        "source": "deterministic generator research/python/make_fixture.py",
        "symbol": "BTCUSDT (label only; not real market data)",
        "interval": "1d",
        "retrieved_at": "2026-11-27T00:00:00Z",
        "rows": len(rows),
        "start": rows[0]["timestamp"],
        "end": rows[-1]["timestamp"],
        "limitations": [
            "Synthetic prices are generated by a fixed formula, not observed market prices.",
            "No live market claim; used only for deterministic offline verification.",
        ],
    }
    provenance_path = path.with_suffix(".provenance.json")
    provenance_path.write_text(json.dumps(provenance, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps({"csv": str(path), "provenance": str(provenance_path), "rows": len(rows)}, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
